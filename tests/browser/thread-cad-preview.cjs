/* Display the exported STEP, preserve its identity and invalidate stale jobs. */
const { chromium } = require('/opt/homebrew/lib/node_modules/@playwright/test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const url = process.env.THREAD_TOOL_URL || 'http://127.0.0.1:8148/tools/thread-visualizer-sizer/';
(async () => {
    const browser = await chromium.launch({ headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
    try {
        const context = await browser.newContext({ viewport: { width: 1400, height: 1100 }, serviceWorkers: 'block' });
        await context.grantPermissions(['clipboard-read', 'clipboard-write']);
        const page = await context.newPage();
        page.setDefaultTimeout(20000);
        const errors = [], requests = [];
        page.on('pageerror', (error) => errors.push(error.message));
        page.on('console', (message) => { if (message.type() === 'error') console.log('console:', message.text()); });
        page.on('request', (request) => requests.push(request.url()));
        await page.goto(url);
        await page.locator('#tool-main[data-boot-state="ready"]').waitFor({ timeout: 60000 });
        assert.equal(requests.some((path) => /thread-cad|three-0|replicad/.test(path)), false);
        await page.locator('#spec-feature').selectOption('external');
        await page.locator('#spec-depth').fill('6');
        await page.waitForFunction(() => document.getElementById('spec-output').dataset.stale === 'false');
        await page.locator('#open-step').click();
        await page.locator('#step-length').fill('6');
        assert.match(await page.locator('#spec-note').innerText(), /FINISHED LEAD-IN CHAMFER: BOTH ENDS/);
        assert.match(await page.locator('#spec-note').innerText(), /not a rolling-blank instruction/);
        await page.locator('#open-step').click();
        await page.locator('#copy-detailed-note').click();
        assert.equal(await page.evaluate(() => navigator.clipboard.readText()), await page.locator('#spec-note').innerText());
        const noteDownload = page.waitForEvent('download');
        await page.locator('#export-results').click();
        await (await noteDownload).saveAs('/private/tmp/thread-cad-note.csv');
        assert.ok(fs.readFileSync('/private/tmp/thread-cad-note.csv', 'utf8').includes('"' + (await page.locator('#spec-note').innerText()).replaceAll('"', '""') + '"'));
        await page.locator('#open-step').click();
        const preview = async () => {
            await page.locator('#preview-thread-step').click();
            await page.waitForFunction(() => !document.getElementById('download-thread-step').disabled || document.getElementById('cancel-thread-step').hidden, null, { timeout: 95000 });
            assert.equal(await page.locator('#download-thread-step').isEnabled(), true, await page.locator('#step-status').innerText());
            assert.equal(await page.locator('#step-view canvas').count(), 1, await page.locator('#step-view-info').innerText());
        };
        await preview();
        await page.locator('#step-options').screenshot({ path: '/private/tmp/thread-step-inline-desktop.png' });
        assert.match(await page.locator('#step-preview-callout').innerText(), /M10x1.5 RH external L6mm CHAMFER BOTH/);
        assert.equal(await page.locator('#step-view canvas').evaluate((canvas) => Number(canvas.dataset.triangles) > 100), true);
        await page.locator('#step-preview').screenshot({ path: '/private/tmp/thread-cad-preview-external.png' });
        const event = page.waitForEvent('download');
        await page.locator('#download-thread-step').click();
        const download = await event;
        await download.saveAs('/private/tmp/thread-previewed-chamfer.step');
        assert.match(fs.readFileSync('/private/tmp/thread-previewed-chamfer.step', 'utf8'), /M10x1.5 RH external L6mm CHAMFER BOTH/);
        assert.match(download.suggestedFilename(), /representative-v2\.step$/);
        await page.locator('#step-view-section').click();
        assert.equal(await page.locator('#step-view canvas').getAttribute('data-section'), 'true');
        await page.locator('#step-preview').screenshot({ path: '/private/tmp/thread-cad-preview-external-section.png' });
        await page.locator('#step-view-edges').click();
        assert.equal(await page.locator('#step-view-edges').getAttribute('aria-pressed'), 'true');
        const sectionDownload = page.waitForEvent('download');
        await page.locator('#download-thread-step').click();
        await (await sectionDownload).saveAs('/private/tmp/thread-previewed-section.step');
        assert.deepEqual(fs.readFileSync('/private/tmp/thread-previewed-section.step'), fs.readFileSync('/private/tmp/thread-previewed-chamfer.step'), 'Section and edges cannot change the STEP bytes');
        await page.locator('#step-view canvas').focus();
        const before = await page.locator('#step-view canvas').getAttribute('data-frames');
        await page.keyboard.press('ArrowRight');
        await page.keyboard.press('+');
        assert.ok(Number(await page.locator('#step-view canvas').getAttribute('data-frames')) > Number(before));
        await page.locator('#step-view-reset').click();
        await page.locator('#step-specimen').selectOption('internal');
        assert.equal(await page.locator('#download-thread-step').isDisabled(), true);
        assert.equal(await page.locator('#step-preview').isVisible(), false);
        assert.match(await page.locator('#spec-note').innerText(), /FINISHED ENTRY CHAMFER/);
        await preview();
        await page.locator('#step-view-section').click();
        await page.locator('#step-preview').screenshot({ path: '/private/tmp/thread-cad-preview-internal-section.png' });
        for (const theme of ['light', 'dark']) {
            await page.setViewportSize({ width: 320, height: 800 });
            await page.evaluate((theme) => document.body.dataset.theme = theme, theme);
            await page.waitForTimeout(200);
            assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
            await page.locator('#step-preview').screenshot({ path: `/private/tmp/thread-cad-preview-${theme}-mobile.png` });
        }
        const idleFrames = await page.locator('#step-view canvas').getAttribute('data-frames');
        await page.waitForTimeout(350);
        assert.equal(await page.locator('#step-view canvas').getAttribute('data-frames'), idleFrames, 'No idle render loop');
        await page.locator('#step-view canvas').evaluate((canvas) => canvas.dispatchEvent(new Event('webglcontextlost', { cancelable: true })));
        assert.match(await page.locator('#step-view').innerText(), /checked STEP is still available/);
        assert.equal(await page.locator('#download-thread-step').isEnabled(), true);
        await page.locator('#step-end-options > summary').click();
        await page.locator('[data-help-for="step-chamfer-depth"]').focus();
        await page.keyboard.press('Enter');
        assert.match(await page.locator('#step-chamfer-depth-tooltip').innerText(), /0.05 pitch/);
        await page.keyboard.press('Escape');
        await page.locator('#step-chamfer-angle').fill('0');
        assert.equal(await page.locator('#preview-thread-step').isDisabled(), true);
        assert.equal(await page.locator('#download-thread-step').isDisabled(), true);
        assert.doesNotMatch(await page.locator('#spec-note').innerText(), /REPRESENTATIVE CAD SPECIMEN/);
        await page.locator('#step-chamfer-angle').fill('45');
        await page.locator('#step-end-style').selectOption('square');
        assert.match(await page.locator('#spec-note').innerText(), /SQUARE ENDS/);
        await page.locator('#preview-thread-step').click();
        await page.locator('#cancel-thread-step').click();
        assert.match(await page.locator('#step-status').innerText(), /Canceled/);
        assert.equal(await page.locator('#download-thread-step').isDisabled(), true);
        await page.locator('#preview-thread-step').click();
        await page.locator('#step-length').fill('7');
        assert.equal(await page.locator('#step-preview').isVisible(), false);
        assert.equal(await page.locator('#download-thread-step').isDisabled(), true);
        await page.locator('#preview-thread-step').click();
        await page.locator('#open-print').click();
        assert.equal(await page.locator('#step-options').getAttribute('open'), null);
        assert.equal(await page.locator('#cancel-thread-step').getAttribute('hidden'), '');
        assert.equal(await page.locator('#download-thread-step').isDisabled(), true);
        await page.waitForTimeout(300);
        assert.equal(await page.locator('#step-preview').getAttribute('hidden'), '', 'A canceled job must not resurrect the collapsed preview');
        assert.deepEqual(errors, []);
        console.log('PASS STEP preview, embedded identification, chamfers and detail-note copying, section, keyboard, mobile themes, stale/cancel handling.');
    } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exit(1); });
